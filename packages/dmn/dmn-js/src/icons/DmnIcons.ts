/** 注册表形态 → 图标 SVG（未收录类型返回空串，消费方自担兜底） */
export function dmnIconHtml(meta: ShapeTypeMeta, size = 18, fill = 'currentColor'): string {
  const body = DRG_ICON_BODIES[metaId(meta)];
  if (!body) {
    return '';
  }
  return svgShell(`<g fill="${fill}">${body}</g>`, 32, size);
}

/** palette / context pad 元素条目 html（currentColor 随容器文字色，悬停反馈可见） */
export function dmnEntryHtml(meta: ShapeTypeMeta, size = 18): string {
  return entryShell(dmnIconHtml(meta, size));
}
